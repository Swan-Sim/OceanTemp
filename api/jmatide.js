const MAX_KM = 60;
const km = (a, b, c, d) => { const R = 6371, r = Math.PI / 180, x = Math.sin((c - a) * r / 2) ** 2 + Math.cos(a * r) * Math.cos(c * r) * Math.sin((d - b) * r / 2) ** 2; return 2 * R * Math.asin(Math.sqrt(x)); };

// 고정폭 한 줄 → { y, m, d, hourly[24](cm), hi:[[hh,mm,cm]], lo:[...] }
function parseLine(line) {
  if (line.length < 136) return null;
  const n3 = (s) => { s = s.trim(); return s === '' ? null : parseInt(s, 10); };
  const hourly = []; for (let i = 0; i < 24; i++) hourly.push(n3(line.slice(i * 3, i * 3 + 3)));
  const y = 2000 + parseInt(line.slice(72, 74), 10), m = parseInt(line.slice(74, 76), 10), d = parseInt(line.slice(76, 78), 10);
  const ev = (start) => { const out = []; for (let k = 0; k < 4; k++) { const p = start + k * 7; const t = line.slice(p, p + 4), h = line.slice(p + 4, p + 7);
    if (t === '9999' || h.trim() === '999') continue; const hh = parseInt(t.slice(0, 2), 10), mm = parseInt(t.slice(2, 4), 10), v = n3(h);
    if (Number.isFinite(hh) && Number.isFinite(mm) && v != null) out.push([hh, mm, v]); } return out; };
  if (!(m >= 1 && m <= 12 && d >= 1 && d <= 31)) return null;
  return { y, m, d, hourly, hi: ev(80), lo: ev(108) };
}

async function loadYear(code, year) {
  const key = `jmatide:${year}:${code}`;
  try { const [{ result }] = await redisPipeline([['GET', key]]); if (result) return JSON.parse(result); } catch (_) {}
  const url = `https://www.data.jma.go.jp/kaiyou/data/db/tide/suisan/txt/${year}/${code}.txt`;
  const c = new AbortController(); const tm = setTimeout(() => c.abort(), 20000);
  let text = null;
  try { const r = await fetch(url, { signal: c.signal, headers: { 'User-Agent': 'otemp.app (tide table, once a year)' } }); if (r.ok) text = await r.text(); }
  catch (_) {} finally { clearTimeout(tm); }
  if (!text) return null;
  const days = text.split(/\r?\n/).map(parseLine).filter(Boolean);
  if (days.length < 300) return null;
  const all = days.flatMap(d => d.hourly).filter(v => v != null);
  const mean = all.reduce((a, b) => a + b, 0) / all.length; // 그 해 평균(≈ 평균해면, 조위표 기준면 위 cm)
  const data = { code, year, mean: +mean.toFixed(1), days: days.map(d => [d.m, d.d, d.hourly, d.hi, d.lo]) };
  try { await redisPipeline([['SET', key, JSON.stringify(data), 'EX', String(400 * 86400)]]); } catch (_) {}
  return data;
}

module.exports = async function handler(req, res) {
  const lat = parseFloat(req.query.lat), lon = parseFloat(req.query.lon);
  const send = (code, o, cache) => { res.setHeader('Cache-Control', cache || 'no-store'); res.status(code).json(o); };
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return send(400, { ok: false, error: 'lat/lon' });
  const near = STATIONS.map(([code, name, la, lo]) => ({ code, name, dist: km(lat, lon, la, lo) })).sort((a, b) => a.dist - b.dist)[0];
  if (!near || near.dist > MAX_KM) return send(200, { ok: false, error: 'no_station' }, 's-maxage=86400');
  // 일본 시각(JST) 기준으로 오늘 -3일 ~ +9일
  const jstNow = Date.now() + 9 * 3600e3;
  const from = Math.floor(jstNow / 86400e3) * 86400e3 - 3 * 86400e3, to = from + 13 * 86400e3;
  const years = [...new Set([new Date(from).getUTCFullYear(), new Date(to).getUTCFullYear()])];
  const loaded = (await Promise.all(years.map(y => loadYear(near.code, y)))).filter(Boolean);
  if (!loaded.length) return send(200, { ok: false, error: 'no_data' }, 's-maxage=3600');
  const mean = loaded[0].mean;
  const series = [], hilo = [];
  loaded.forEach(Y => Y.days.forEach(([m, d, hourly, hi, lo]) => {
    const day0 = Date.UTC(Y.year, m - 1, d);
    if (day0 < from || day0 >= to) return;
    hourly.forEach((v, h) => { if (v != null) series.push({ x: day0 + h * 3600e3, y: +((v - mean) / 100).toFixed(2) }); });
    hi.forEach(([hh, mm, v]) => hilo.push({ x: day0 + (hh * 60 + mm) * 60e3, y: +((v - mean) / 100).toFixed(2), type: 'high' }));
    lo.forEach(([hh, mm, v]) => hilo.push({ x: day0 + (hh * 60 + mm) * 60e3, y: +((v - mean) / 100).toFixed(2), type: 'low' }));
  }));
  series.sort((a, b) => a.x - b.x); hilo.sort((a, b) => a.x - b.x);
  // x = 일본 현지 시각(JST)을 UTC처럼 쓴 ms(사이트 표의 x와 같은 방식)
  send(200, { ok: true, station: { code: near.code, name: near.name, dist: +near.dist.toFixed(1) }, tz: 'JST', series, hilo,
    source: '出典：気象庁ホームページ（潮位表）' }, 's-maxage=21600, stale-while-revalidate=86400');
};
